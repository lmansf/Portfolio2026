"""Build data/pipeline/metrics.sql from data/pipeline/metrics.json.

The site's metrics (catch rate, fraud rate, and the rest) are defined once,
in data/pipeline/metrics.json, as numerator / denominator over the fraud_*
tables. Three readers use that one file:

  * assets/metrics.js computes them for the /live page;
  * this script writes data/pipeline/metrics.sql: a DuckDB macro per metric
    (`SELECT catch_rate(fraud_caught, fraud) FROM fraud_daily`) and the
    fraud_metrics view (one row per metric, over fraud_totals). The SQL
    source editors load it in the browser and the nightly data run loads
    it to test the numbers and the site copy that quotes them;
  * the catalog page lists them.

    python3 scripts/build_metrics.py           # rewrite metrics.sql
    python3 scripts/build_metrics.py --check   # exit 1 if it's stale or a definition is broken
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METRICS = ROOT / "data" / "pipeline" / "metrics.json"
OUT = ROOT / "data" / "pipeline" / "metrics.sql"
SNAPSHOT_TABLES = ROOT / "data" / "console" / "snapshot-tables.json"
DEFAULT_TABLE = "fraud_totals"
VIEW = "fraud_metrics"

IDENT = re.compile(r"[a-z_][a-z0-9_]*")
EXPR = re.compile(r"[a-z_][a-z0-9_]*(?:\s*[+-]\s*[a-z_][a-z0-9_]*)*")


def load():
    return json.loads(METRICS.read_text(encoding="utf-8"))


def columns_of_tables():
    specs = json.loads(SNAPSHOT_TABLES.read_text(encoding="utf-8"))
    return {name: [c[0] for c in spec["columns"]] for name, spec in specs.items()
            if not name.startswith("_")}


def terms(expr):
    return IDENT.findall(expr)


def parts(metric, table=DEFAULT_TABLE):
    """(numerator, denominator) expressions for `metric` on `table`."""
    over = metric["tables"].get(table, {})
    return over.get("numerator", metric["numerator"]), over.get("denominator", metric["denominator"])


def params(metric):
    """The macro's parameters: each column of the default definition, in order."""
    seen = []
    for t in terms(metric["numerator"]) + terms(metric["denominator"]):
        if t not in seen:
            seen.append(t)
    return seen


def definition(metric, table=DEFAULT_TABLE):
    num, den = parts(metric, table)
    wrap = lambda e: f"({e})" if re.search(r"[+-]", e) else e  # noqa: E731
    return f"{wrap(num)} / {wrap(den)}"


def problems(defs, tables=None):
    tables = tables or columns_of_tables()
    out = []
    for name, m in defs["metrics"].items():
        if not IDENT.fullmatch(name):
            out.append(f"{name}: a metric name must be lower_snake_case")
        for key in ("label", "description", "numerator", "denominator"):
            if not m.get(key):
                out.append(f"{name}: needs a {key}")
        if DEFAULT_TABLE not in m.get("tables", {}):
            out.append(f"{name}: every metric is defined on {DEFAULT_TABLE} (it's a row of {VIEW})")
        for table in m.get("tables", {}):
            if table not in tables:
                out.append(f"{name}: no table {table} in data/console/snapshot-tables.json")
                continue
            for expr in parts(m, table):
                if not EXPR.fullmatch(expr or ""):
                    out.append(f"{name} on {table}: {expr!r} must be columns joined by + or -")
                    continue
                gone = [t for t in terms(expr) if t not in tables[table]]
                if gone:
                    out.append(f"{name} on {table}: {table} has no column {', '.join(gone)}")
    for c in defs.get("claims", []):
        if c.get("metric") not in defs["metrics"]:
            out.append(f"claim {c.get('quote')!r}: no metric {c.get('metric')!r}")
        if not c.get("pages") or not c.get("quote"):
            out.append(f"claim {c.get('quote')!r}: needs pages and a quote")
        if not isinstance(c.get("min"), (int, float)) or not isinstance(c.get("max"), (int, float)):
            out.append(f"claim {c.get('quote')!r}: needs a numeric min and max")
    return out


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def build(defs):
    lines = [
        "-- Generated by scripts/build_metrics.py from data/pipeline/metrics.json. Don't edit;",
        "-- change the JSON and rerun the script.",
        "--",
        "-- One macro per metric, so a query can use the site's own definition:",
        "--   SELECT day, catch_rate(fraud_caught, fraud) FROM fraud_daily;",
        f"-- and {VIEW}: every metric over {DEFAULT_TABLE}, one row each.",
        "",
    ]
    for name, m in defs["metrics"].items():
        num, den = m["numerator"], m["denominator"]
        lines.append(f"-- {m['label']}: {m['description']}")
        lines.append(f"CREATE OR REPLACE MACRO {name}({', '.join(params(m))}) AS "
                     f"CAST({num} AS DOUBLE) / nullif({den}, 0);")
    lines.append("")
    selects = []
    for name, m in defs["metrics"].items():
        num, den = parts(m)
        selects.append(
            f"SELECT {sql_str(name)} AS metric, {sql_str(m['label'])} AS label,\n"
            f"       {sql_str(definition(m))} AS definition,\n"
            f"       CAST({num} AS DOUBLE) AS numerator, CAST({den} AS DOUBLE) AS denominator,\n"
            f"       {name}({', '.join(params(m))}) AS value\n"
            f"FROM {DEFAULT_TABLE}")
    lines.append(f"CREATE OR REPLACE VIEW {VIEW} AS\n" + "\nUNION ALL\n".join(selects) + ";")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    defs = load()
    bad = problems(defs)
    if bad:
        sys.exit("data/pipeline/metrics.json:\n  " + "\n  ".join(bad))
    text = build(defs)
    if check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("data/pipeline/metrics.sql is stale: run python3 scripts/build_metrics.py")
        print("data/pipeline/metrics.sql is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
